import asyncio
import json
import logging
from pathlib import Path
from tqdm import tqdm

# Import DeepTutor RAG tool
import sys
project_root = Path(__file__).parent.parent.parent
sys.path.append(str(project_root))
from src.tools.rag_tool import rag_search

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("DeepTutor-Eval")

class Evaluator:
    def __init__(self, dataset_path: str):
        self.dataset_path = Path(dataset_path)
        
    def load_dataset(self):
        with open(self.dataset_path, 'r', encoding='utf-8') as f:
            return json.load(f)
            
    def calculate_hit_rate(self, generated: str, ground_truth: str) -> float:
        """
        Simple keyword overlap metric for Phase 4 baseline.
        In production, use RAGAS 'Faithfulness' or 'Answer Relevancy'.
        """
        gen_words = set(generated.lower().split())
        truth_words = set(ground_truth.lower().split())
        
        # Calculate intersection over truth (Recall-ish)
        if not truth_words:
            return 0.0
        
        intersection = gen_words.intersection(truth_words)
        return len(intersection) / len(truth_words)

    async def run(self):
        logger.info(f"Loading dataset from {self.dataset_path}")
        dataset = self.load_dataset()
        
        results = []
        total_score = 0
        
        logger.info("Starting Evaluation...")
        for item in tqdm(dataset, desc="Evaluating"):
            query = item["question"]
            truth = item["ground_truth"]
            
            try:
                # Execute RAG Search
                # We use 'hybrid' or 'advanced' mode
                response = await rag_search(
                    query=query, 
                    mode="hybrid",  # Using hybrid as AdvancedRAG logic is inside rag_tool now
                    only_need_context=False
                )
                
                answer = response["answer"]
                
                # Calculate Metric
                score = self.calculate_hit_rate(answer, truth)
                total_score += score
                
                results.append({
                    "id": item["id"],
                    "query": query,
                    "score": score,
                    "answer_snippet": answer[:100] + "..."
                })
                
            except Exception as e:
                logger.error(f"Error evaluating query '{query}': {e}")
                
        avg_score = total_score / len(dataset) if dataset else 0
        logger.info(f"Evaluation Complete. Average Hit Rate (Recall proxy): {avg_score:.4f}")
        
        # Save detailed results
        result_file = self.dataset_path.parent / "eval_results.json"
        with open(result_file, 'w', encoding='utf-8') as f:
            json.dump({"summary": {"avg_score": avg_score}, "details": results}, f, indent=2)
        logger.info(f"Results saved to {result_file}")

